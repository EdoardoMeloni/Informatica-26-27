public class Risposta {
    private String testoRisposta;
    private int indice;
    private boolean corretta;

    public int getIndice() {
        return indice;
    }

    public String getTestoRisposta() {
        return indice + ") " + testoRisposta;
    }

    public boolean isCorretta() {
        return corretta;
    }




}
